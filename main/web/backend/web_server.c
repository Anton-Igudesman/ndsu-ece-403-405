// Change the LED operating mode for the current terminal owner
static esp_err_t handle_terminal_set_mode(
   httpd_req_t *request,
   const cJSON *root
)
{
   int socket_fd = httpd_req_to_sockfd(request);

   // Log incoming mode activation requests and ownership status
   bool is_owner = terminal_session_manager_is_owner(socket_fd);

   ESP_LOGI(
      LOG_TAG,
      "Command Mode request: socket=%d owner=%d",
      socket_fd,
      is_owner
   );

   if (!is_owner)
   {
      ESP_LOGW(
         LOG_TAG,
         "Command Mode rejected: socket=%d is not terminal owner",
         socket_fd
      );

      return ESP_ERR_INVALID_STATE;
   }

   // Execute the mode change and report the result
   esp_err_t status = web_terminal_execute(root);

   ESP_LOGI(
      LOG_TAG,
      "Command Mode result: socket=%d status=%s",
      socket_fd,
      esp_err_to_name(status)
   );

   return status;
}

// Return the requesting terminal client's current ownership status
static esp_err_t handle_terminal_get_ownership(
   httpd_req_t *request,
   const cJSON *root
)
{
   (void)root;
   int socket_fd = httpd_req_to_sockfd(request);

   cJSON *response = cJSON_CreateObject();
   if (response == NULL) return ESP_ERR_NO_MEM;

   // Report ownership relative to requesting connection
   cJSON_AddStringToObject(response, "event", "terminal_ownership_changed");
   cJSON_AddBoolToObject(response, "is_owner", terminal_session_manager_is_owner(socket_fd));
   cJSON_AddBoolToObject(response, "owner_present", terminal_session_manager_get_owner() >= 0);

   // Report whether the requesting device has a pending control request
   cJSON_AddBoolToObject(
      response,
      "request_pending",
      terminal_session_manager_has_pending_request(socket_fd)
   );

   // Include device identification in the initial ownership response
   esp_err_t ip_status = add_terminal_ip_fields(
      response,
      socket_fd
   );

   if (ip_status != ESP_OK)
   {
      ESP_LOGW(
         LOG_TAG,
         "Unable to resolve terminal IP addresses: %s",
         esp_err_to_name(ip_status)
      );
   }

   esp_err_t status = send_websocket_json(
      socket_fd,
      response
   );

   cJSON_Delete(response);

   return status;
}

