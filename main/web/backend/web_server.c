// Resolve and execute a terminal action using the registered handlers
static esp_err_t dispatch_terminal_action(
   httpd_req_t *request,
   const cJSON *root,
   const char **event
)
{
   int socket_fd = httpd_req_to_sockfd(request);
   const cJSON *action = cJSON_GetObjectItemCaseSensitive(root, "action");

   *event = "terminal_result";

   if (!cJSON_IsString(action))
   {
      // Pixel commands require terminal ownership
      if (!terminal_session_manager_is_owner(socket_fd)) return ESP_ERR_INVALID_STATE;
      return web_terminal_execute(root);
   }

   const size_t action_count = sizeof(s_terminal_actions) / sizeof(s_terminal_actions[0]);
   for (size_t i = 0; i < action_count; i++)
   {
      const terminal_action_entry_t *entry = &s_terminal_actions[i];

      if (strcmp(action->valuestring, entry->name) != 0) continue;

      *event = entry->event;
      
      // Execute the matched action and handle ownership notifications
      return execute_terminal_action(entry, request, root);   
   }

   return ESP_ERR_NOT_SUPPORTED;
}

// Parse a MAC address string into six bytes
static esp_err_t parse_mac_address(
   const char *mac_string,
   uint8_t mac[6]
)
{
   if (mac_string == NULL || mac == NULL)
      return ESP_ERR_INVALID_ARG;

   unsigned int bytes[6];
   int consumed = 0;

   // Parse six hexadecimal bytes and record the number of characters consumed
   int parsed = sscanf(
      mac_string,
      "%2x:%2x:%2x:%2x:%2x:%2x%n",
      &bytes[0],
      &bytes[1],
      &bytes[2],
      &bytes[3],
      &bytes[4],
      &bytes[5],
      &consumed
   );

   // Require all six bytes, exactly 17 characters, and no trailing data
   if (parsed != 6 || consumed != 17 ||
       mac_string[consumed] != '\0')
      return ESP_ERR_INVALID_ARG;

   // Convert the parsed hexadecimal values into individual bytes
   for (size_t index = 0; index < 6; index++)
      mac[index] = (uint8_t)bytes[index];

   return ESP_OK;
}

// Process an administrator controller authorization action
static esp_err_t process_admin_controller_action(const cJSON *root)
{
   if (root == NULL) return ESP_ERR_INVALID_ARG;

   // Extract the requested action and target MAC address from the JSON message
   const cJSON *action = cJSON_GetObjectItemCaseSensitive(
      root,
      "action"
   );

   const cJSON *mac_string = cJSON_GetObjectItemCaseSensitive(
      root,
      "mac"
   );

   // Both JSON fields must contain strings
   if (!cJSON_IsString(action) || !cJSON_IsString(mac_string))
      return ESP_ERR_INVALID_ARG;

   uint8_t client_mac[6];

   // Convert the MAC address string into six bytes
   esp_err_t status = parse_mac_address(
      mac_string->valuestring,
      client_mac
   );

   if (status != ESP_OK) return status;

   // strcmp() returns 0 when both strings match.
   // Approve the pending client when the action is "approve_controller".
   if (strcmp(action->valuestring, "approve_controller") == 0)
      return client_manager_approve_controller(client_mac);

   // Deny the pending client when the action is "deny_controller".
   if (strcmp(action->valuestring, "deny_controller") == 0)
      return client_manager_deny_controller(client_mac);

   // Reject any action that the server does not recognize
   return ESP_ERR_NOT_SUPPORTED;
}

// Serialize and send a JSON object over an established WebSocket
static esp_err_t send_websocket_json(
   int socket_fd,
   const cJSON *response
)
{
   if (s_server == NULL || socket_fd < 0 || response == NULL) return ESP_ERR_INVALID_ARG;

   char *message = cJSON_PrintUnformatted(response);
   if (message == NULL) return ESP_ERR_NO_MEM;

   httpd_ws_frame_t frame = 
   {
      .final = true,
      .fragmented = false,
      .type = HTTPD_WS_TYPE_TEXT,
      .payload = (uint8_t *)message,
      .len = strlen(message)
   };

   esp_err_t status = httpd_ws_send_frame_async(
      s_server,
      socket_fd,
      &frame
   );

   cJSON_free(message);
   
   return status;
}

// Send a JSON result to the requesting WebSocket client
static esp_err_t send_websocket_response(
   int socket_fd,
   const char *event,
   esp_err_t action_status
)
{
   if (s_server == NULL || socket_fd < 0 || event == NULL) return ESP_ERR_INVALID_ARG;

   cJSON *response = cJSON_CreateObject();
   if (response == NULL) return ESP_ERR_NO_MEM;

   cJSON_AddStringToObject(response, "event", event);
   cJSON_AddBoolToObject(response, "success", action_status == ESP_OK);

   // Include the ESP-IDF error description when execution fails
   if (action_status != ESP_OK)
   {
      cJSON_AddStringToObject(
         response,
         "error",
         esp_err_to_name(action_status)
      );
   }

   esp_err_t status = send_websocket_json(
      socket_fd,
      response
   );

   cJSON_Delete(response);

   return status;
}

// Notify connected terminal when ownership changes
static esp_err_t notify_terminal_ownership_changed(void)
{
   int socket_fds[TERMINAL_MAX_CLIENTS];

   size_t client_count = terminal_session_manager_get_clients(
      socket_fds,
      TERMINAL_MAX_CLIENTS
   );

   esp_err_t final_status = ESP_OK;

   int owner_id = terminal_session_manager_get_owner();
   for (size_t i = 0; i < client_count; i++)
   {
      cJSON *response = cJSON_CreateObject();
      if (response == NULL) return ESP_ERR_NO_MEM;

      // Each client receives its own ownership status
      cJSON_AddStringToObject(response, "event", "terminal_ownership_changed");

      // Report each device's pending-request status alongside ownership changes
      cJSON_AddBoolToObject(
         response,
         "request_pending",
         terminal_session_manager_has_pending_request(socket_fds[i])
      );

      // All connections from a device must report the same ownership state
      bool is_owner = terminal_session_manager_is_owner(socket_fds[i]);

      cJSON_AddBoolToObject(response, "is_owner", is_owner);
      cJSON_AddBoolToObject(response, "owner_present", owner_id >= 0);

      // Include device identification in each ownership notification
      esp_err_t ip_status = add_terminal_ip_fields(
         response,
         socket_fds[i]
      );

      if (ip_status != ESP_OK)
      {
         ESP_LOGW(
            LOG_TAG,
            "Unable to resolve terminal IP addresses: %s",
            esp_err_to_name(ip_status)
         );
      }

      esp_err_t status = send_websocket_json(
         socket_fds[i],
         response
      );

      // Log ownership notification delivery for each terminal connection
      ESP_LOGI(
         LOG_TAG,
         "Ownership notification: socket=%d owner=%d present=%d status=%s",
         socket_fds[i],
         is_owner,
         owner_id >= 0,
         esp_err_to_name(status)
      );

      cJSON_Delete(response);

      if (status != ESP_OK) final_status = status;
   }

   return final_status;
}

