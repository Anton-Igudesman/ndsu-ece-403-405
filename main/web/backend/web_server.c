/*
   Add an authenticated administrator WebSocket to the active registry.

   If the same device reconnects, its existing entry is updated rather
   than consuming another WebSocket slot.
*/
static esp_err_t register_admin_websocket(
   int socket_fd,
   const uint8_t mac[6]
)
{
   if (socket_fd < 0 || mac == NULL)
      return ESP_ERR_INVALID_ARG;

   // Update the existing entry if this administrator reconnects.
   for (size_t admin = 0; admin < WEB_MAX_CLIENTS; admin++)
   {
      if (memcmp(
            s_admin_websockets[admin].mac,
            mac,
            sizeof(s_admin_websockets[admin].mac)
         ) == 0)
      {
         s_admin_websockets[admin].socket_fd = socket_fd;
         return ESP_OK;
      }
   }

   // Otherwise use the first available WebSocket slot.
   for (size_t admin = 0; admin < WEB_MAX_CLIENTS; admin++)
   {
      if (s_admin_websockets[admin].socket_fd < 0)
      {
         s_admin_websockets[admin].socket_fd = socket_fd;

         memcpy(
            s_admin_websockets[admin].mac,
            mac,
            sizeof(s_admin_websockets[admin].mac)
         );

         return ESP_OK;
      }
   }

   return ESP_ERR_NO_MEM;
}

/*
   Remove an administrator WebSocket from the active registry.
*/
static void remove_admin_websocket(
   int socket_fd
)
{
   for (size_t admin = 0; admin < WEB_MAX_CLIENTS; admin++)
   {
      if (s_admin_websockets[admin].socket_fd == socket_fd)
      {
         s_admin_websockets[admin].socket_fd = -1;

         memset(
            s_admin_websockets[admin].mac,
            0,
            sizeof(s_admin_websockets[admin].mac)
         );

         return;
      }
   }
}

// Reset all administrator WebSocket slots to an unused state.
static void initialize_admin_websockets(void)
{
   for (size_t admin = 0; admin < WEB_MAX_CLIENTS; admin++)
   {
      s_admin_websockets[admin].socket_fd = -1;

      memset(
         s_admin_websockets[admin].mac,
         0,
         sizeof(s_admin_websockets[admin].mac)
      );
   }
}

/*
   Get the IPv4 address of the device that sent an HTTP request.

   The request socket identifies the remote TCP connection,
   allowing the server to determine which WiFi client sent it.
*/
static esp_err_t get_request_client_ip(
   httpd_req_t *request,
   esp_ip4_addr_t *client_ip
)
{
   if (request == NULL || client_ip == NULL)
      return ESP_ERR_INVALID_ARG;

   // Get the socket associated with this HTTP request.
   int socket_fd = httpd_req_to_sockfd(request);

   struct sockaddr_storage client_address = {0};
   socklen_t address_length = sizeof(client_address);

   // Read the remote device address from the TCP connection.
   if (getpeername(
         socket_fd,
         (struct sockaddr *)&client_address,
         &address_length) != 0) return ESP_FAIL;
   
      if (client_address.ss_family == AF_INET)
   {
      struct sockaddr_in *client_ipv4 =
         (struct sockaddr_in *)&client_address;

      client_ip->addr = client_ipv4->sin_addr.s_addr;

      return ESP_OK;
   }

   if (client_address.ss_family == AF_INET6)
   {
      struct sockaddr_in6 *client_ipv6 =
         (struct sockaddr_in6 *)&client_address;

      const uint8_t *address_bytes =
         client_ipv6->sin6_addr.s6_addr;

      /*
         IPv4-mapped IPv6 addresses use ::ffff:a.b.c.d.
         Extract the final four bytes so the address can be
         matched against the SoftAP DHCP client registry.
      */
      if (IN6_IS_ADDR_V4MAPPED(&client_ipv6->sin6_addr))
      {
         memcpy(
            &client_ip->addr,
            &address_bytes[12],
            sizeof(client_ip->addr)
         );

         return ESP_OK;
      }
   }

   ESP_LOGE(
      LOG_TAG,
      "Unable to resolve HTTP client to an IPv4 address"
   );

   return ESP_ERR_NOT_SUPPORTED;
}

/*
   Send one frontend file embedded in the firmware.

   The start and end linker symbols identify the file's location
   and size inside the firmware image.
*/
static esp_err_t send_embedded_file(
   httpd_req_t *request,
   const uint8_t *file_start,
   const uint8_t *file_end,
   const char *content_type
)
{
   if (request == NULL ||
      file_start == NULL ||
      file_end == NULL ||
      content_type == NULL ||
      file_end < file_start)
   {
      return ESP_ERR_INVALID_ARG;
   }

   httpd_resp_set_type(
      request,
      content_type
   );

   return httpd_resp_send(
      request,
      (const char *)file_start,
      file_end - file_start
   );
}

// Serve the Svelte application entry page
static esp_err_t frontend_index_get_handler(httpd_req_t *request)
{
   return send_embedded_file(
      request,
      index_html_start,
      index_html_end,
      "text/html"
   );
}

// Serve the compiled Svelte JavaScript bundle
static esp_err_t frontend_js_get_handler(httpd_req_t *request)
{
   return send_embedded_file(
      request,
      app_js_start,
      app_js_end,
      "application/javascript"
   );
}

// Serve the compiled Tailwind stylesheet
static esp_err_t frontend_css_get_handler(httpd_req_t *request)
{
   return send_embedded_file(
      request,
      app_css_start,
      app_css_end,
      "text/css"
   );
}

/*
   Get clients currently connected to the ESP32 WiFi access point.

   The WiFi driver provides associated station MAC addresses.
   ESP-NETIF resolves those addresses to DHCP-assigned IPs.
*/
static esp_err_t get_connected_clients(
   web_client_t *clients,
   size_t max_clients,
   size_t *client_count
)
{
   if (clients == NULL ||
      client_count == NULL ||
      max_clients == 0)
   {
      return ESP_ERR_INVALID_ARG;
   }

   *client_count = 0;

   // Get stations currently associated with the access point
   wifi_sta_list_t station_list = {0};

   esp_err_t status = esp_wifi_ap_get_sta_list(
      &station_list
   );

   if (status != ESP_OK) return status;

   size_t count = station_list.num;

   if (count > max_clients)
      count = max_clients;

   // Store MAC/IP pairs for ESP-NETIF to resolve
   esp_netif_pair_mac_ip_t network_list[WEB_MAX_CLIENTS] = {0};

   for (size_t client = 0; client < count; client++)
   {
      memcpy(
         network_list[client].mac,
         station_list.sta[client].mac,
         sizeof(network_list[client].mac)
      );
   }

   // Get the ESP32 SoftAP network interface
   esp_netif_t *ap_netif = esp_netif_get_handle_from_ifkey(
      "WIFI_AP_DEF"
   );

   if (ap_netif == NULL) return ESP_ERR_INVALID_STATE;

   // Resolve station MAC addresses to DHCP-assigned IPv4 addresses
   status = esp_netif_dhcps_get_clients_by_mac(
      ap_netif,
      (int)count,
      network_list
   );

   if (status != ESP_OK) return status;

   // Copy resolved client information into application structures
   for (size_t client = 0; client < count; client++)
   {
      memcpy(
         clients[client].mac,
         network_list[client].mac,
         sizeof(clients[client].mac)
      );

      clients[client].ip = network_list[client].ip;
   }

   *client_count = count;

   return ESP_OK;
}

// Convert connected client MAC/IP information into dashboard JSON
static cJSON *create_clients_json(
   const web_client_t *clients,
   size_t client_count
)
{
   if (clients == NULL && client_count > 0)
      return NULL;

   cJSON *client_array = cJSON_CreateArray();
   if (client_array == NULL) return NULL;

   for (size_t client = 0; client < client_count; client++)
   {
      char mac_address[18];
      char ip_address[16];

      snprintf(
         mac_address,
         sizeof(mac_address),
         "%02X:%02X:%02X:%02X:%02X:%02X",
         clients[client].mac[0],
         clients[client].mac[1],
         clients[client].mac[2],
         clients[client].mac[3],
         clients[client].mac[4],
         clients[client].mac[5]
      );

      snprintf(
         ip_address,
         sizeof(ip_address),
         IPSTR,
         IP2STR(&clients[client].ip)
      );

      cJSON *client_json = cJSON_CreateObject();

      if (client_json == NULL)
      {
         cJSON_Delete(client_array);
         return NULL;
      }

      cJSON_AddStringToObject(
         client_json,
         "mac",
         mac_address
      );

      cJSON_AddStringToObject(
         client_json,
         "ip",
         ip_address
      );

      cJSON_AddItemToArray(
         client_array,
         client_json
      );
   }

   return client_array;
}

// Handle administrator login requests
static esp_err_t admin_login_post_handler(httpd_req_t *request)
{
   if (request == NULL) return ESP_ERR_INVALID_ARG;

   // Reject request bodies that cannot fit in the local buffer
   if (request->content_len <= 0 ||
      request->content_len >= 256)
   {
      httpd_resp_send_err(
         request,
         HTTPD_400_BAD_REQUEST,
         "Invalid request"
      );

      return ESP_OK;
   }

   char request_body[256];

   // Read the JSON request body
   int received = httpd_req_recv(
      request,
      request_body,
      request->content_len
   );

   if (received <= 0)
   {
      httpd_resp_send_err(
         request,
         HTTPD_400_BAD_REQUEST,
         "Unable to read request"
      );

      return ESP_OK;
   }

   request_body[received] = '\0';

   // Parse the submitted JSON credentials
   cJSON *root = cJSON_Parse(request_body);

   if (root == NULL)
   {
      httpd_resp_send_err(
         request,
         HTTPD_400_BAD_REQUEST,
         "Invalid JSON"
      );

      return ESP_OK;
   }

   const cJSON *username = cJSON_GetObjectItemCaseSensitive(
      root,
      "username"
   );

   const cJSON *password = cJSON_GetObjectItemCaseSensitive(
      root,
      "password"
   );

   bool credentials_valid =
      cJSON_IsString(username) &&
      cJSON_IsString(password) &&
      strcmp(username->valuestring, WEB_ADMIN_USERNAME) == 0 &&
      strcmp(password->valuestring, WEB_ADMIN_PASSWORD) == 0;

   cJSON_Delete(root);

   if (!credentials_valid)
   {
      httpd_resp_set_status(
         request,
         "401 Unauthorized"
      );

      return httpd_resp_send(
         request,
         "Unauthorized",
         HTTPD_RESP_USE_STRLEN
      );
   }

      // Refresh the registry so the login request can be matched to its WiFi client.
   esp_err_t status = client_manager_sync_connected_clients();

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to refresh clients during administrator login: %s",
         esp_err_to_name(status)
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to identify client"
      );
   }

   esp_ip4_addr_t client_ip;

   // Get the source IP of the device that submitted the administrator login.
   status = get_request_client_ip(
      request,
      &client_ip
   );

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to get administrator client IP"
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to identify client"
      );
   }

   // Associate administrator authorization with the matching WiFi client.
   status = client_manager_set_admin_by_ip(
      &client_ip
   );

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to authorize administrator client: %s",
         esp_err_to_name(status)
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to authorize client"
      );
   }

   ESP_LOGI(
      LOG_TAG,
      "Administrator login successful"
   );

   httpd_resp_set_type(
      request,
      "application/json"
   );

   return httpd_resp_send(
      request,
      "{\"authenticated\":true}",
      HTTPD_RESP_USE_STRLEN
   );
}

// Handle GET /api/admin/clients and return the current client list as JSON
static esp_err_t admin_clients_get_handler(httpd_req_t *request)
{
   if (request == NULL) return ESP_ERR_INVALID_ARG;

   // Refresh the new client registry before returning connected devices
   esp_err_t manager_status = client_manager_sync_connected_clients();

   if (manager_status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Client manager sync failed: %s",
         esp_err_to_name(manager_status)
      );
   }

   web_client_t clients[WEB_MAX_CLIENTS];
   size_t client_count = 0;

   // Retrieve the current clients from the WiFi access point
   esp_err_t status = get_connected_clients(
      clients,
      WEB_MAX_CLIENTS,
      &client_count
   );

   if (status != ESP_OK) return status;

   // Convert the client information into the dashboard API format
   cJSON *clients_json = create_clients_json(
      clients,
      client_count
   );

   if (clients_json == NULL) return ESP_ERR_NO_MEM;

   char *response = cJSON_PrintUnformatted(
      clients_json
   );

   cJSON_Delete(clients_json);

   if (response == NULL) return ESP_ERR_NO_MEM;

   httpd_resp_set_type(
      request,
      "application/json"
   );

   status = httpd_resp_send(
      request,
      response,
      HTTPD_RESP_USE_STRLEN
   );

   cJSON_free(response);

   return status;
}

/*
   Handle WebSocket connections used by authenticated administrators.

   A WebSocket is added to the administrator registry only when its
   source device has already completed administrator authentication.
*/
static esp_err_t websocket_handler(httpd_req_t *request)
{
   if (request == NULL) return ESP_ERR_INVALID_ARG;

   if (request->method == HTTP_GET)
   {
      esp_ip4_addr_t client_ip;

      // Identify the device opening this WebSocket connection.
      esp_err_t status = get_request_client_ip(
         request,
         &client_ip
      );

      if (status != ESP_OK)
      {
         ESP_LOGW(
            LOG_TAG,
            "Unable to identify WebSocket client"
         );

         return status;
      }

      uint8_t client_mac[6];

      status = client_manager_get_mac_by_ip(
         &client_ip,
         client_mac
      );

      if (status != ESP_OK)
      {
         ESP_LOGW(
            LOG_TAG,
            "WebSocket client was not found in the client registry"
         );

         return status;
      }

      // Only authenticated administrators may register an admin WebSocket.
      if (!client_manager_is_admin(client_mac))
      {
         ESP_LOGW(
            LOG_TAG,
            "Rejected WebSocket from unauthenticated client"
         );

         return ESP_ERR_INVALID_STATE;
      }

      int socket_fd = httpd_req_to_sockfd(request);

      status = register_admin_websocket(
         socket_fd,
         client_mac
      );

      if (status != ESP_OK)
      {
         ESP_LOGE(
            LOG_TAG,
            "Failed to register administrator WebSocket: %s",
            esp_err_to_name(status)
         );

         return status;
      }

      ESP_LOGI(
         LOG_TAG,
         "Administrator WebSocket connected: %02X:%02X:%02X:%02X:%02X:%02X",
         client_mac[0],
         client_mac[1],
         client_mac[2],
         client_mac[3],
         client_mac[4],
         client_mac[5]
      );

      return ESP_OK;
   }

   httpd_ws_frame_t frame = {0};

   // Read the frame header so control frames such as CLOSE can be handled.
   esp_err_t status = httpd_ws_recv_frame(
      request,
      &frame,
      0
   );

   if (status != ESP_OK)
   {
      ESP_LOGW(
         LOG_TAG,
         "Failed to receive WebSocket frame: %s",
         esp_err_to_name(status)
      );

      return status;
   }

   if (frame.type == HTTPD_WS_TYPE_CLOSE)
   {
      int socket_fd = httpd_req_to_sockfd(request);

      remove_admin_websocket(socket_fd);

      ESP_LOGI(
         LOG_TAG,
         "Administrator WebSocket disconnected"
      );
   }

   return ESP_OK;
}

// Register one HTTP endpoint with the web server
static esp_err_t register_uri_handler(
   const char *uri,
   httpd_method_t method,
   esp_err_t (*handler)(httpd_req_t *request),
   bool is_websocket
)
{
   if (uri == NULL || handler == NULL)
      return ESP_ERR_INVALID_ARG;

   httpd_uri_t uri_config =
   {
      .uri = uri,
      .method = method,
      .handler = handler,
      .user_ctx = NULL,
      .is_websocket = is_websocket
   };

   return httpd_register_uri_handler(
      s_server,
      &uri_config
   );
}

// Register all HTTP endpoints handled by the web server
static esp_err_t register_uri_handlers(void)
{
   esp_err_t status = register_uri_handler(
      "/",
      HTTP_GET,
      frontend_index_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/assets/app.js",
      HTTP_GET,
      frontend_js_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/assets/app.css",
      HTTP_GET,
      frontend_css_get_handler,
      false
   );
   if (status != ESP_OK) return status;
   
   status = register_uri_handler(
      "/api/admin/login",
      HTTP_POST,
      admin_login_post_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/api/admin/clients",
      HTTP_GET,
      admin_clients_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/ws",
      HTTP_GET,
      websocket_handler,
      true
   );
   if (status != ESP_OK) return status;

   return ESP_OK;
}

