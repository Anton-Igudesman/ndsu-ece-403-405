esp_err_t web_server_start(void)
{
   if (s_initialized) return ESP_OK;

   httpd_config_t server_config = HTTPD_DEFAULT_CONFIG();

   esp_err_t status = httpd_start(
      &s_server,
      &server_config
   );

   if (status != ESP_OK) return status;

   // Register all HTTP endpoints after the server is created
   status = register_uri_handlers();

   if (status != ESP_OK)
   {
      httpd_stop(s_server);
      s_server = NULL;

      return status;
   }

   s_initialized = true;

   ESP_LOGI(
      LOG_TAG,
      "HTTP server started"
   );

   return ESP_OK;
}

/*
   Notify the administrator dashboard that the WiFi client list changed.

   The dashboard receives this event and requests /api/admin/clients
   to retrieve the updated client list.
*/
esp_err_t web_server_notify_clients_changed(void)
{
   // Nothing to notify if the server or WebSocket is unavailable
   if (!s_initialized ||
      s_websocket_fd < 0)
   {
      return ESP_OK;
   }

   static const char message[] =
      "{\"event\":\"clients_changed\"}";

   httpd_ws_frame_t frame =
   {
      .final = true,
      .fragmented = false,
      .type = HTTPD_WS_TYPE_TEXT,
      .payload = (uint8_t *)message,
      .len = sizeof(message) - 1U
   };

   return httpd_ws_send_frame_async(
      s_server,
      s_websocket_fd,
      &frame
   );
}

esp_err_t web_server_stop(void)
{
   if (!s_initialized) return ESP_OK;

   esp_err_t status = httpd_stop(s_server);
   if (status != ESP_OK) return status;

   s_server = NULL;
   s_websocket_fd = -1;
   s_initialized = false;

   ESP_LOGI(
      LOG_TAG,
      "HTTP server stopped"
   );

   return ESP_OK;
}