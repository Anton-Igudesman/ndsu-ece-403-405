// Convert connected client MAC/IP information into dashboard JSON
static cJSON *create_clients_json(
   const client_record_t *clients,
   size_t client_count
)
{
   if (clients == NULL && client_count > 0)
      return NULL;

   cJSON *client_array = cJSON_CreateArray();
   if (client_array == NULL) return NULL;

   for (size_t client = 0; client < client_count; client++)
   {
      char mac_address[18];
      char ip_address[16];

      snprintf(
         mac_address,
         sizeof(mac_address),
         "%02X:%02X:%02X:%02X:%02X:%02X",
         clients[client].mac[0],
         clients[client].mac[1],
         clients[client].mac[2],
         clients[client].mac[3],
         clients[client].mac[4],
         clients[client].mac[5]
      );

      snprintf(
         ip_address,
         sizeof(ip_address),
         IPSTR,
         IP2STR(&clients[client].ip)
      );

      cJSON *client_json = cJSON_CreateObject();

      if (client_json == NULL)
      {
         cJSON_Delete(client_array);
         return NULL;
      }

      cJSON_AddStringToObject(
         client_json,
         "mac",
         mac_address
      );

      cJSON_AddStringToObject(
         client_json,
         "ip",
         ip_address
      );

      cJSON_AddNumberToObject(
         client_json,
         "auth_state",
         clients[client].auth_state
      );

      cJSON_AddItemToArray(
         client_array,
         client_json
      );
   }

   return client_array;
}

// Handle administrator login requests
static esp_err_t admin_login_post_handler(httpd_req_t *request)
{
   if (request == NULL) return ESP_ERR_INVALID_ARG;

   // Reject request bodies that cannot fit in the local buffer
   if (request->content_len <= 0 ||
      request->content_len >= 256)
   {
      httpd_resp_send_err(
         request,
         HTTPD_400_BAD_REQUEST,
         "Invalid request"
      );

      return ESP_OK;
   }

   char request_body[256];

   // Read the JSON request body
   int received = httpd_req_recv(
      request,
      request_body,
      request->content_len
   );

   if (received <= 0)
   {
      httpd_resp_send_err(
         request,
         HTTPD_400_BAD_REQUEST,
         "Unable to read request"
      );

      return ESP_OK;
   }

   request_body[received] = '\0';

   // Parse the submitted JSON credentials
   cJSON *root = cJSON_Parse(request_body);

   if (root == NULL)
   {
      httpd_resp_send_err(
         request,
         HTTPD_400_BAD_REQUEST,
         "Invalid JSON"
      );

      return ESP_OK;
   }

   const cJSON *username = cJSON_GetObjectItemCaseSensitive(
      root,
      "username"
   );

   const cJSON *password = cJSON_GetObjectItemCaseSensitive(
      root,
      "password"
   );

   bool credentials_valid =
      cJSON_IsString(username) &&
      cJSON_IsString(password) &&
      strcmp(username->valuestring, WEB_ADMIN_USERNAME) == 0 &&
      strcmp(password->valuestring, WEB_ADMIN_PASSWORD) == 0;

   cJSON_Delete(root);

   if (!credentials_valid)
   {
      httpd_resp_set_status(
         request,
         "401 Unauthorized"
      );

      return httpd_resp_send(
         request,
         "Unauthorized",
         HTTPD_RESP_USE_STRLEN
      );
   }

      // Refresh the registry so the login request can be matched to its WiFi client.
   esp_err_t status = client_manager_sync_connected_clients();

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to refresh clients during administrator login: %s",
         esp_err_to_name(status)
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to identify client"
      );
   }

   esp_ip4_addr_t client_ip;

   // Get the source IP of the device that submitted the administrator login.
   status = get_request_client_ip(
      request,
      &client_ip
   );

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to get administrator client IP"
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to identify client"
      );
   }

   // Associate administrator authorization with the matching WiFi client.
   status = client_manager_set_admin_by_ip(
      &client_ip
   );

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to authorize administrator client: %s",
         esp_err_to_name(status)
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to authorize client"
      );
   }

   ESP_LOGI(
      LOG_TAG,
      "Administrator login successful"
   );

   httpd_resp_set_type(
      request,
      "application/json"
   );

   return httpd_resp_send(
      request,
      "{\"authenticated\":true}",
      HTTPD_RESP_USE_STRLEN
   );
}

// Handle GET /api/admin/clients and return the current client list as JSON
static esp_err_t admin_clients_get_handler(httpd_req_t *request)
{
   if (request == NULL) return ESP_ERR_INVALID_ARG;

   // Restrict the client registry to authenticated administrators
   if (!is_admin_http_request(request))
   {
      return httpd_resp_send_err(
         request,
         HTTPD_403_FORBIDDEN,
         "Administrator authorization required"
      );
   }

   // Refresh the new client registry before returning connected devices
   esp_err_t status = client_manager_sync_connected_clients();

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Client manager sync failed: %s",
         esp_err_to_name(status)
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to refresh connected clients"
      );
   }

   client_record_t clients[CLIENT_MANAGER_MAX_CLIENTS];
   size_t client_count = 0;

   // Retrieve the current clients from WiFi access point
   status = client_manager_get_clients(
      clients,
      CLIENT_MANAGER_MAX_CLIENTS,
      &client_count
   );

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to retrieve connected clients: %s",
         esp_err_to_name(status)
      );

      return httpd_resp_send_err(
         request,
         HTTPD_500_INTERNAL_SERVER_ERROR,
         "Unable to retrieve connected clients"
      );
   }

   // Convert the client information into the dashboard API format
   cJSON *clients_json = create_clients_json(
      clients,
      client_count
   );

   if (clients_json == NULL) return ESP_ERR_NO_MEM;

   char *response = cJSON_PrintUnformatted(
      clients_json
   );

   cJSON_Delete(clients_json);

   if (response == NULL) return ESP_ERR_NO_MEM;

   httpd_resp_set_type(
      request,
      "application/json"
   );

   status = httpd_resp_send(
      request,
      response,
      HTTPD_RESP_USE_STRLEN
   );

   cJSON_free(response);

   return status;
}

/*
   Handle WebSocket connections used by authenticated administrators.

   A WebSocket is added to the administrator registry only when its
   source device has already completed administrator authentication.
*/
static esp_err_t websocket_handler(httpd_req_t *request)
{
   if (request == NULL) return ESP_ERR_INVALID_ARG;

   if (request->method == HTTP_GET)
   {

      uint8_t client_mac[6];

      // Identify device opening the WebSocket connection
      esp_err_t status = get_request_client_mac(
         request,
         client_mac
      );

      if (status != ESP_OK)
      {
         ESP_LOGW(
            LOG_TAG,
            "Unable to identify WebSocket client: %s",
            esp_err_to_name(status)
         );

         return status;
      }

      // Only authenticated administrators may register an admin WebSocket.
      if (!client_manager_is_admin(client_mac))
      {
         ESP_LOGW(
            LOG_TAG,
            "Rejected WebSocket from unauthenticated client"
         );

         return ESP_ERR_INVALID_STATE;
      }

      int socket_fd = httpd_req_to_sockfd(request);

      status = register_admin_websocket(
         socket_fd,
         client_mac
      );

      if (status != ESP_OK)
      {
         ESP_LOGE(
            LOG_TAG,
            "Failed to register administrator WebSocket: %s",
            esp_err_to_name(status)
         );

         return status;
      }

      ESP_LOGI(
         LOG_TAG,
         "Administrator WebSocket connected: %02X:%02X:%02X:%02X:%02X:%02X",
         client_mac[0],
         client_mac[1],
         client_mac[2],
         client_mac[3],
         client_mac[4],
         client_mac[5]
      );

      return ESP_OK;
   }

   httpd_ws_frame_t frame = {0};

   // Read the frame header so control frames such as CLOSE can be handled.
   esp_err_t status = httpd_ws_recv_frame(
      request,
      &frame,
      0
   );

   if (status != ESP_OK)
   {
      ESP_LOGW(
         LOG_TAG,
         "Failed to receive WebSocket frame: %s",
         esp_err_to_name(status)
      );

      return status;
   }

   int socket_fd = httpd_req_to_sockfd(request);

   if (frame.type == HTTPD_WS_TYPE_CLOSE)
   {

      remove_admin_websocket(socket_fd);

      ESP_LOGI(
         LOG_TAG,
         "Administrator WebSocket disconnected"
      );

      return ESP_OK;
   }

   // Ignore control frames and unsupported message types
   if (frame.type != HTTPD_WS_TYPE_TEXT) return ESP_OK;

   // Reject fragmented messages
   if (frame.fragmented || !frame.final) return ESP_ERR_NOT_SUPPORTED;

   // Limit incoming JSON messages to 512 bytes
   if (frame.len == 0 || frame.len > 512) return ESP_ERR_INVALID_SIZE;

   // Allocate extra byte for terminating null character
   char message[513];

   frame.payload = (uint8_t *)message;

   // Read the actual WebSocket message payload
   esp_err_t receive_status = httpd_ws_recv_frame(
      request,
      &frame,
      512
   );

   if (receive_status != ESP_OK) return receive_status;

   // Terminate the received bytes so cJSON can parse the string
   message[frame.len] = '\0';

   esp_err_t process_status = process_admin_websocket_message(
      socket_fd,
      message
   );

   if (process_status != ESP_OK)
   {
      ESP_LOGW(
         LOG_TAG,
         "Administrator WebSocket action failed: %s",
         esp_err_to_name(process_status)
      );
   }

   // Send the action result to admin who submitted
   esp_err_t response_status = send_admin_websocket_response(
      socket_fd,
      process_status
   );

   if (response_status != ESP_OK)
   {
      ESP_LOGW(
         LOG_TAG,
         "Failed to send administrator WebSocket response: %s",
         esp_err_to_name(response_status)
      );

      return response_status;
   }

   return ESP_OK;
}

// Register one HTTP endpoint with the web server
static esp_err_t register_uri_handler(
   const char *uri,
   httpd_method_t method,
   esp_err_t (*handler)(httpd_req_t *request),
   bool is_websocket
)
{
   if (uri == NULL || handler == NULL)
      return ESP_ERR_INVALID_ARG;

   httpd_uri_t uri_config =
   {
      .uri = uri,
      .method = method,
      .handler = handler,
      .user_ctx = NULL,
      .is_websocket = is_websocket
   };

   return httpd_register_uri_handler(
      s_server,
      &uri_config
   );
}

// Register all HTTP endpoints handled by the web server
static esp_err_t register_uri_handlers(void)
{
   esp_err_t status = register_uri_handler(
      "/",
      HTTP_GET,
      frontend_index_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/assets/app.js",
      HTTP_GET,
      frontend_js_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/assets/app.css",
      HTTP_GET,
      frontend_css_get_handler,
      false
   );
   if (status != ESP_OK) return status;
   
   status = register_uri_handler(
      "/api/admin/login",
      HTTP_POST,
      admin_login_post_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/api/admin/clients",
      HTTP_GET,
      admin_clients_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/api/controller/request",
      HTTP_POST,
      controller_request_post_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/api/controller/status",
      HTTP_GET,
      controller_status_get_handler,
      false
   );
   if (status != ESP_OK) return status;

   status = register_uri_handler(
      "/ws",
      HTTP_GET,
      websocket_handler,
      true
   );
   if (status != ESP_OK) return status;

   return ESP_OK;
}

