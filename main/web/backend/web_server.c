esp_err_t web_server_start(void)
{
   if (s_initialized) return ESP_OK;
   initialize_admin_websockets();

   esp_err_t status = client_manager_init();

   if (status != ESP_OK)
   {
      ESP_LOGE(
         LOG_TAG,
         "Failed to initialize client manager: %s",
         esp_err_to_name(status)
      );

      return status;
   }

   // Initialize terminal connection and ownership tracking
   status = terminal_session_manager_init();
   if (status != ESP_OK) return status;

   httpd_config_t server_config = HTTPD_DEFAULT_CONFIG();

   // Allow additional endpoints for the LED terminal
   server_config.max_uri_handlers = 12;

   server_config.close_fn = web_socket_close_callback;

   status = httpd_start(
      &s_server,
      &server_config
   );

   if (status != ESP_OK) return status;

   // Register all HTTP endpoints after the server is created
   status = register_uri_handlers();

   if (status != ESP_OK)
   {
      httpd_stop(s_server);
      s_server = NULL;

      return status;
   }

   s_initialized = true;

   ESP_LOGI(
      LOG_TAG,
      "HTTP server started"
   );

   return ESP_OK;
}

/*
   Notify all administrator dashboards that the WiFi client list changed.

   Each active administrator WebSocket receives the event. WebSockets
   that can no longer be reached are removed from the registry.
*/
esp_err_t web_server_notify_clients_changed(void)
{
   if (!s_initialized)
      return ESP_OK;

   static const char message[] =
      "{\"event\":\"clients_changed\"}";

   httpd_ws_frame_t frame =
   {
      .final = true,
      .fragmented = false,
      .type = HTTPD_WS_TYPE_TEXT,
      .payload = (uint8_t *)message,
      .len = sizeof(message) - 1U
   };

   esp_err_t final_status = ESP_OK;

   for (size_t admin = 0; admin < WEB_MAX_CLIENTS; admin++)
   {
      int socket_fd = s_admin_websockets[admin].socket_fd;

      // Skip unused administrator WebSocket slots.
      if (socket_fd < 0)
         continue;

      // Remove WebSocket entries no longer recognized by the HTTP server
      if (!is_admin_websocket_connected(socket_fd))
      {
         remove_admin_websocket(socket_fd);
         continue;
      }

      esp_err_t status = httpd_ws_send_frame_async(
         s_server,
         socket_fd,
         &frame
      );

      if (status != ESP_OK)
      {
         ESP_LOGW(
            LOG_TAG,
            "Administrator WebSocket send failed: %s",
            esp_err_to_name(status)
         );

         remove_admin_websocket(socket_fd);
         final_status = status;
      }
   }

   return final_status;
}

esp_err_t web_server_stop(void)
{
   if (!s_initialized) return ESP_OK;

   esp_err_t status = httpd_stop(s_server);

   if (status != ESP_OK)
      return status;

   // Clear server and administrator connection state after shutdown.
   s_server = NULL;
   initialize_admin_websockets();
   s_initialized = false;

   ESP_LOGI(
      LOG_TAG,
      "HTTP server stopped"
   );

   return ESP_OK;
}