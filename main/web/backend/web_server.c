#define WEB_ADMIN_USERNAME "admin"
#define WEB_ADMIN_PASSWORD "admin"
#define WEB_MAX_CLIENTS 8U

// -----------------------------------------------------------
// ---------------- Module Scope Definitions -----------------
// -----------------------------------------------------------

static const char *LOG_TAG = "web_server";

static httpd_handle_t s_server = NULL;
static bool s_initialized = false;

// MAC and DHCP-assigned IP information for one connected WiFi client
typedef struct
{
   uint8_t mac[6];
   esp_ip4_addr_t ip;
} web_client_t;

// File descriptor for the currently connected administrator WebSocket client
static int s_websocket_fd = -1;

// Embedded Svelte frontend files generated by the Vite production build
extern const uint8_t index_html_start[]
   asm("_binary_index_html_start");

extern const uint8_t index_html_end[]
   asm("_binary_index_html_end");

extern const uint8_t app_js_start[]
   asm("_binary_app_js_start");

extern const uint8_t app_js_end[]
   asm("_binary_app_js_end");

extern const uint8_t app_css_start[]
   asm("_binary_app_css_start");

extern const uint8_t app_css_end[]
   asm("_binary_app_css_end");

